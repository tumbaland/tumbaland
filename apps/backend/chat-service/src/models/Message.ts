import { Schema, model, Document, Types } from 'mongoose';

export type MessageKind = 'text' | 'media' | 'system' | 'collage' | 'reminder';

/** What the sender asked this message to arrive with: around its bubble, and across the screen. */
export const MESSAGE_EFFECTS = ['hearts', 'confetti', 'kisses'] as const;
export type MessageEffect = (typeof MESSAGE_EFFECTS)[number];

export interface IAttachment {
  /** file-service path, e.g. `chat/<groupId>/<conversationId>/<uuid>/original.jpg`. */
  fileId: string;
  /** Still frame for a video, generated in the browser at upload time. */
  posterFileId?: string;
  /** Downscaled display copy for an image (webp), generated by the service. */
  thumbnailFileId?: string;
  mimetype: string;
  /** The uploaded file's name. Kept for documents, which are shown by name. */
  name?: string;
  sizeBytes: number;
  width?: number;
  height?: number;
  durationMs?: number;
  /** The album this file was saved to, once Album has it. Name kept for the "In Rome" mark. */
  albumId?: string | null;
  albumName?: string | null;
}

/** The collage a `collage` message invites the others to: "Make a collage together". */
export interface ICollageCard {
  /** The collage's id in Album. */
  id: string;
  title: string;
}

/**
 * The plan a `reminder` message is about, as the journal had it when the
 * reminder fell due. A copy, not a link: the thread shows what everyone was
 * reminded of even after the plan is moved or deleted.
 */
export interface IPlanCard {
  /** The plan's id in the journal (relationship-service). */
  id: string;
  title: string;
  /** YYYY-MM-DD, the first day */
  date: string;
  /** YYYY-MM-DD, the last day of a trip; null for one day */
  endDate?: string | null;
  /** HH:mm, null all day */
  time: string | null;
  timeZone: string;
  place: string | null;
}

export interface IReaction {
  /** `User._id`. One reaction per person per message. */
  userId: string;
  /** Denormalised for display, so drawing a reaction row needs no lookup. */
  name: string;
  emoji: string;
  at: Date;
}

export interface IMessage extends Document {
  _id: Types.ObjectId;
  conversationId: string;
  /** `User._id`. The identity key: who sent this. */
  senderId: string;
  /** Display and audit only. Never the identity check. */
  senderEmail: string;
  senderName: string;
  kind: MessageKind;
  body: string;
  attachments: IAttachment[];
  replyTo?: string | null;
  effect?: MessageEffect | null;
  collage?: ICollageCard | null;
  plan?: IPlanCard | null;
  reactions: IReaction[];
  /**
   * Generated by the client before the first send attempt and repeated on
   * every retry. A dropped response is indistinguishable from a dropped
   * request, so without this a flaky connection posts the same message twice.
   * See the unique index below.
   */
  clientId: string;
  editedAt?: Date | null;
  deletedAt?: Date | null;
  createdAt: Date;
  updatedAt: Date;
}

const AttachmentSchema = new Schema<IAttachment>(
  {
    fileId: { type: String, required: true },
    posterFileId: { type: String, default: null },
    thumbnailFileId: { type: String, default: null },
    mimetype: { type: String, required: true },
    name: { type: String, default: null },
    sizeBytes: { type: Number, required: true, min: 0 },
    width: { type: Number, default: null },
    height: { type: Number, default: null },
    durationMs: { type: Number, default: null },
    albumId: { type: String, default: null },
    albumName: { type: String, default: null }
  },
  { _id: false }
);

const ReactionSchema = new Schema<IReaction>(
  {
    userId: { type: String, required: true },
    name: { type: String, default: '' },
    emoji: { type: String, required: true },
    at: { type: Date, default: Date.now }
  },
  { _id: false }
);

const MessageSchema = new Schema<IMessage>(
  {
    conversationId: { type: String, required: true },
    senderEmail: { type: String, required: true, lowercase: true },
    senderId: { type: String, required: true },
    senderName: { type: String, default: '' },
    kind: { type: String, enum: ['text', 'media', 'system', 'collage', 'reminder'], default: 'text' },
    body: { type: String, default: '', maxlength: 8000 },
    attachments: { type: [AttachmentSchema], default: [] },
    replyTo: { type: String, default: null },
    effect: { type: String, enum: [...MESSAGE_EFFECTS, null], default: null },
    collage: { type: new Schema<ICollageCard>({ id: String, title: String }, { _id: false }), default: null },
    plan: {
      type: new Schema<IPlanCard>(
        { id: String, title: String, date: String, endDate: String, time: String, timeZone: String, place: String },
        { _id: false }
      ),
      default: null
    },
    reactions: { type: [ReactionSchema], default: [] },
    clientId: { type: String, required: true },
    // A deleted message keeps its row: removing it would renumber nothing but
    // would break `replyTo` and leave a hole in the stream's id sequence.
    editedAt: { type: Date, default: null },
    deletedAt: { type: Date, default: null }
  },
  { timestamps: true }
);

// Paging: newest first within one conversation, cursored on createdAt.
MessageSchema.index({ conversationId: 1, createdAt: -1 });

// Idempotent send. Painful to add once there is data, so it exists from the
// first version.
MessageSchema.index({ conversationId: 1, clientId: 1 }, { unique: true });

// Built for the first version of search, which now matches parts of words
// instead (see searchMessages). Removing it here would not drop it from the
// database, so it stays until it is dropped on purpose.
MessageSchema.index({ body: 'text' });

export const Message = model<IMessage>('Message', MessageSchema);
